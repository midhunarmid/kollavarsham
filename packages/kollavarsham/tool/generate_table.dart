// Regenerates lib/src/data/month_starts.dart from the astronomical engine.
//
// Usage: dart run tool/generate_table.dart
import 'dart:io';

import 'package:kollavarsham/kollavarsham.dart';

/// First and last Kollavarsham years in the table (Gregorian 1899–2101).
const firstYear = 1075;
const lastYear = 1276;

void main() {
  File('lib/src/data/month_starts.dart')
    ..createSync(recursive: true)
    ..writeAsStringSync(generateMonthStartTable());
  stdout.writeln('Wrote ${(lastYear - firstYear + 1) * 12} month starts.');
}

/// Source of `lib/src/data/month_starts.dart`, computed without the table.
String generateMonthStartTable() {
  final cal = KollavarshamCalendar(usePrecomputedTable: false);
  final first = cal
      .dayNumberOfGregorian(cal.monthStart(firstYear, MalayalamMonth.chingam));
  final lengths = StringBuffer();
  for (var year = firstYear; year <= lastYear; year++) {
    for (final month in MalayalamMonth.values) {
      lengths.writeCharCode(0x30 + cal.monthLength(year, month) - 29);
    }
  }
  final encoded = lengths.toString();
  final lines = <String>[
    for (var i = 0; i < encoded.length; i += 72)
      "    '${encoded.substring(i, i + 72 > encoded.length ? encoded.length : i + 72)}'",
  ];
  return '''
// GENERATED by tool/generate_table.dart; do not edit.

/// Kollavarsham year of the first month (Chingam) in the table.
const int monthStartTableFirstYear = $firstYear;

/// Day number (days since 1970-01-01) of Chingam 1, $firstYear.
const int monthStartTableFirstDay = $first;

/// Length of each month from Chingam $firstYear to Karkidakam $lastYear,
/// one character per month: '0' = 29 days … '3' = 32 days.
const String monthStartTableLengths =
${lines.join('\n')};
''';
}
