"""Generates reference data with the Swiss Ephemeris.

1. packages/kollavarsham/test/fixtures/sankranti_1900_2100.csv: one row per
   sankranti (the Sun entering a sidereal sign, Swiss "Lahiri" mode), used
   to cross-check the package's own solar theory:

       sign,utc
       0,1900-04-13T05:12:33Z

2. packages/kollavarsham/lib/src/astro/delta_t_table.dart: ΔT (TT − UT) on
   1 January of each year 1900–2100. These are the IERS observed values and,
   beyond them, the Stephenson–Morrison–Hohenkerk (2016) extrapolation, as
   tabulated by the Swiss Ephemeris. Only the numbers are used; no Swiss
   Ephemeris code ships with the package.

Requires `pip install pyswisseph`. Uses the built-in Moshier ephemeris, so no
data files are needed (solar accuracy well under 1 arc-second).

Usage: python tool/generate_reference.py
"""

import datetime
import os

import swisseph as swe

PKG = os.path.join(os.path.dirname(__file__), "..", "packages", "kollavarsham")
OUT = os.path.join(PKG, "test", "fixtures", "sankranti_1900_2100.csv")
DELTA_T_OUT = os.path.join(PKG, "lib", "src", "astro", "delta_t_table.dart")


def write_delta_t() -> None:
    values = [
        swe.deltat(swe.julday(year, 1, 1, 0.0)) * 86400.0
        for year in range(1900, 2101)
    ]
    lines = [
        "// GENERATED by tool/generate_reference.py; do not edit.",
        "",
        "/// First year covered by [deltaTTable].",
        "const int deltaTTableStartYear = 1900;",
        "",
        "/// ΔT (TT − UT) in seconds on 1 January of each year from",
        "/// [deltaTTableStartYear] to 2100: IERS observed values, then the",
        "/// Stephenson–Morrison–Hohenkerk (2016) extrapolation.",
        "const List<double> deltaTTable = [",
    ]
    lines += [f"  {v:.2f}," for v in values]
    lines += ["];", ""]
    with open(DELTA_T_OUT, "w", newline="\n", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"wrote {len(values)} delta-T values to {os.path.normpath(DELTA_T_OUT)}")


def main() -> None:
    write_delta_t()
    swe.set_sid_mode(swe.SIDM_LAHIRI)
    flags = swe.FLG_MOSEPH | swe.FLG_SIDEREAL
    jd = swe.julday(1900, 1, 1, 0.0)
    end = swe.julday(2101, 1, 1, 0.0)
    rows = []
    while True:
        lon = swe.calc_ut(jd, swe.SUN, flags)[0][0]
        sign = (int(lon // 30) + 1) % 12
        jd = swe.solcross_ut(sign * 30.0, jd, flags)
        if jd >= end:
            break
        y, m, d, h = swe.revjul(jd)
        t = datetime.datetime(y, m, d) + datetime.timedelta(hours=h)
        rows.append(f"{sign},{t.strftime('%Y-%m-%dT%H:%M:%SZ')}")
        jd += 1.0
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", newline="\n") as f:
        f.write("sign,utc\n")
        f.write("\n".join(rows) + "\n")
    print(f"wrote {len(rows)} rows to {os.path.normpath(OUT)}")


if __name__ == "__main__":
    main()
